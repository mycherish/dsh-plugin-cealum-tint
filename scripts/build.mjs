/**
 * Cealum Tint build — two outputs, no other toolchain:
 *   index.js   Host half — ESM bundle for Node, `@deepseek-ai/*` external
 *              because the kernel supplies those packages at runtime.
 *   client.js  Browser half — CJS bundle wrapped in the DSH ModuleLoader
 *              envelope; `react*` and the ui primitives stay external because
 *              the page's module table provides them (verbatims in
 *              DEVELOPMENT-PLAN §6), and JSX rides `react/jsx-runtime`.
 *
 * Run with `node scripts/build.mjs` (or `npm run build`).
 */
import { readFile, stat, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { build } from 'esbuild'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))

const shared = {
  bundle: true,
  logLevel: 'warning',
  legalComments: 'none',
  define: { 'process.env.NODE_ENV': '"production"' },
  absWorkingDir: root,
}

/** Version banner: the artifact must be able to say which build it is. */
const banner = (half) =>
  `/*! ${pkg.name} ${pkg.version} — ${half} half. Generated by scripts/build.mjs; do not edit. */\n`

async function buildHost() {
  await build({
    ...shared,
    entryPoints: [join(root, 'src/host/index.ts')],
    outfile: join(root, 'index.js'),
    format: 'esm',
    platform: 'node',
    target: ['node22'],
    // The Cordis kernel resolves these from its own node_modules.
    external: ['@deepseek-ai/*'],
    sourcemap: false,
    banner: { js: banner('host') },
  })
}

async function buildClient() {
  const result = await build({
    ...shared,
    entryPoints: [join(root, 'src/client/index.tsx')],
    write: false,
    format: 'cjs',
    platform: 'browser',
    target: ['chrome120'],
    jsx: 'automatic',
    // The page's module table owns React and the primitives; everything else
    // in src/ is bundled.
    external: [
      'react',
      'react/jsx-runtime',
      'react-dom',
      'react-dom/client',
      '@deepseek-ai/dsh-client-ui-primitives',
    ],
    minify: true,
    metafile: true,
  })
  const output = result.outputFiles?.[0]
  if (output === undefined) throw new Error('client build produced no output')

  // Indent the bundle into the factory body exactly as the ModuleLoader
  // envelope spec requires: `factory(require)` receives the page's require.
  const body = output.text
    .split('\n')
    .map((line) => (line === '' ? '' : `    ${line}`))
    .join('\n')

  const wrapped = `${banner('browser')}
window.__ModuleLoader__.load({
  // The factory id equals the package name (ui-plugin contract, verified in
  // dsh-config-manager); the *patch row* id ("cealum-tint") is the settings
  // namespace and never appears here.
  id: ${JSON.stringify(pkg.name)},
  factory(require) {
    var module = { exports: {} };
    var exports = module.exports;
    (function (module, exports, require) {
${body}
    })(module, exports, require);
    return module.exports;
  },
});
`

  const target = join(root, 'client.js')
  await writeFile(target, wrapped, 'utf8')
  return {
    target,
    bytes: Buffer.byteLength(wrapped),
    inputs: Object.keys(result.metafile?.inputs ?? {}).length,
  }
}

async function main() {
  await buildHost()
  const client = await buildClient()
  const indexStat = await stat(join(root, 'index.js'))
  const report = [
    `host   index.js   ${(indexStat.size / 1024).toFixed(1)} kB`,
    `client client.js  ${(client.bytes / 1024).toFixed(1)} kB  (${client.inputs} modules)`,
  ]
  console.log(report.join('\n'))
}

await main()
